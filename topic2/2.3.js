const monthNumber = 1;
let result3 = "";

switch (monthNumber) {
    case 1:
        result3 = "January";
        break;
    case 2:
        result3 = "February";
        break;
    case 3:
        result3 = "March";
        break;
    case 4:
        result3 = "April";
        break;
    case 5:
        result3 = "May";
        break;
    case 6:
        result3 = "June";
        break;
    default:
        result3 = "Unknown month";
}

console.log(result3);
