console.log("Привет! Добро пожаловать в отчет о результатах пользователей.");

// ================================
// Объявление данных пользователей
// ================================
const user1 = 'Алиса';
const rightAnswers1 = 17;

const user2 = 'Карл';
const rightAnswers2 = 22;

// ================================
// Максимальный балл
// ================================
const maxRightAnswers = 25;

// ================================
// Заголовок отчета
// ================================
console.log("Отчет по результатам пользователей:");

// ================================
// Процентный результат каждого пользователя
// ================================
const userPercent1 = (rightAnswers1 / maxRightAnswers) * 100;
const userPercent2 = (rightAnswers2 / maxRightAnswers) * 100;

console.log(`${user1} набрал ${userPercent1.toFixed(2)}%`);
console.log(`${user2} набрал ${userPercent2.toFixed(2)}%`);

// ================================
// Проверка, кто набрал больше 20 баллов
// ================================
console.log(`Набрал больше 20 баллов ${user1}?`, rightAnswers1 > 20);
console.log(`Набрал больше 20 баллов ${user2}?`, rightAnswers2 > 20);