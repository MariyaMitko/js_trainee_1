class Book {
    constructor(isbn, title, author, year, genre, pages, rating, firstLine) {
        this.isbn = isbn;
        this.title = title;
        this.author = author;
        this.year = year;
        this.genre = genre;
        this.pages = pages;
        this.rating = rating;
        this.firstLine = firstLine;
    }
}

class Library {
    constructor(books = []) {
        this.books = books;
    }

    printAllTitles() {
        console.log("=== Все книги в библиотеке ===");
        this.books.forEach(book => console.log(book.title));
    }

    printBestBookByAuthor(author) {
        const booksByAuthor = this.books.filter(book => book.author === author);
        if (booksByAuthor.length === 0) {
            console.log(`Книг автора ${author} нет`);
            return;
        }
        const bestBook = booksByAuthor.reduce((best, current) => current.rating > best.rating ? current : best);
        console.log(`Самая популярная книга ${author}: "${bestBook.title}" (рейтинг ${bestBook.rating}/5)`);
    }

    sortByYear() {
        this.books.sort((a, b) => a.year - b.year);
        console.log("\n=== Библиотека отсортирована по году выпуска ===");
        this.books.forEach(book => console.log(`${book.year}: "${book.title}" - ${book.author}`));
    }
}

